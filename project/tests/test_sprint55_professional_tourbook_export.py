def test_pdf_export_has_dynamic_layout_rest_highlighting_and_footer():
    source = _js()
    assert "const preferredLandscape = maxStageChars > 36;" in source
    assert "didParseCell: (hook) => {" in source
    assert 'if (r && r.isRestDay) {' in source
    assert "hook.cell.styles.fillColor = [255, 247, 237];" in source
    assert "doc.text(`Page ${pageNo} / ${totalPages}`" in source
    assert 'TOUR_EXPORT_STRINGS.generatedBy' in source


def test_excel_library_supports_cell_styles():
    html = _html()
    assert 'xlsx-js-style@1.2.0' in html
