from pathlib import Path

BASE_DIR = Path(__file__).resolve().parents[1]
MAP_JS = BASE_DIR / 'frontend' / 'map.js'
INDEX_HTML = BASE_DIR / 'frontend' / 'index.html'


def _js() -> str:
    return MAP_JS.read_text(encoding='utf-8')


def _html() -> str:
    return INDEX_HTML.read_text(encoding='utf-8')


def test_export_strings_table_centralizes_visible_labels():
    source = _js()
    assert 'const TOUR_EXPORT_STRINGS = Object.freeze({' in source
    assert "headerDistanceKm: 'Distance (km)'" in source
    assert "headerCumElevationHm: 'Cum. Elevation (hm)'" in source
    assert "headerTemperatureC: 'Temperature (°C)'" in source
    assert "headerRainMm: 'Rain (mm)'" in source
    assert "headerNotes: 'Notes'" in source
    assert "generatedBy: 'Generated by Touracle'" in source


def test_export_row_model_removes_type_column_and_keeps_rest_day_flag():
    source = _js()
    assert 'isRestDay: !isRide,' in source
    assert 'stage: `${stageStart} -> ${stageDestination}`,' in source
    assert 'distanceKm: roundTo(distanceKm, 1),' in source
    assert 'cumulativeDistanceKm: roundTo(cumulativeDistanceKm, 1),' in source
    assert 'temperatureC: Number.isFinite(tempVal) ? roundTo(tempVal, 1) : null,' in source
    assert "type: isRide ? 'Ride Day' : 'Rest Day'" not in source


