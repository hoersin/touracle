from pathlib import Path

BASE_DIR = Path(__file__).resolve().parents[1]
MAP_JS = BASE_DIR / 'frontend' / 'map.js'
INDEX_HTML = BASE_DIR / 'frontend' / 'index.html'


def _js() -> str:
    return MAP_JS.read_text(encoding='utf-8')


def _html() -> str:
    return INDEX_HTML.read_text(encoding='utf-8')


def test_export_strings_table_centralizes_visible_labels():
    # Export labels are i18n keys export.<name> (English reference in en.js), resolved
    # through TOUR_EXPORT_STRINGS so PDF, Excel and CSV follow the UI language.
    source = _js()
    assert 'const TOUR_EXPORT_STRINGS = new Proxy({}, { get: (_t, k) => (typeof k === \'string\' ? _exportT(`export.${k}`) : undefined) });' in source
    en = (Path(__file__).resolve().parents[1] / 'frontend' / 'i18n' / 'en.js').read_text(encoding='utf-8')
    for key, text in (('headerDistanceKm', 'Distance (km)'), ('headerCumElevationHm', 'Cum. Elevation (hm)'),
                      ('headerTemperatureC', 'Temperature (°C)'), ('headerRainMm', 'Rain (mm)'), ('headerNotes', 'Notes'),
                      ('generatedBy', 'Generated by Touracle')):
        assert f'"export.{key}": "{text}"' in en, key


